_LANGS = {"zh": LANG_ZH, "en": LANG_EN}
_current = "zh"


def set_language(lang: str) -> None:
    global _current
    if lang not in _LANGS:
        raise ValueError(f"不支持的语言：{lang}（可用：{'/'.join(_LANGS)}）")
    _current = lang


def get_language() -> str:
    return _current


def t(key: str, **kwargs) -> str:
    """取词。当前语言缺失该键时回退中文，再缺失则原样返回键名。"""
    text = _LANGS[_current].get(key) or LANG_ZH.get(key) or key
    return text.format(**kwargs) if kwargs else text
